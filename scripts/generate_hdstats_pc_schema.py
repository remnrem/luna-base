#!/usr/bin/env python3
"""Generate the compiled registry for the HDSTATS-PC v2 JSON specification.

The JSON specification is the editable source of truth.  The generated header
contains only the panel/weight-group/feature registry needed to validate Luna's
feature producer; it intentionally contains no fitted-PC labels, orientations,
or component registry.
"""

import argparse
import json
from pathlib import Path


def cpp(value: str) -> str:
    return '"' + value.replace('\\', '\\\\').replace('"', '\\"') + '"'


def fail(source: Path, message: str) -> None:
    raise SystemExit(f"{source}: {message}")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("source", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()

    try:
        document = json.loads(args.source.read_text())
    except (OSError, json.JSONDecodeError) as error:
        fail(args.source, f"invalid JSON: {error}")

    if not isinstance(document, dict) or document.get("format") != "luna-hdstats-pc-spec" or document.get("version") != 2:
        fail(args.source, "expected luna-hdstats-pc-spec version 2")
    if document.get("feature_universe") != "HDSTATS-PC-FEATURES-V2":
        fail(args.source, "expected HDSTATS-PC-FEATURES-V2")

    descriptions = document.get("feature_descriptions")
    panels = document.get("panels")
    derived = document.get("derived_features")
    if not isinstance(descriptions, list) or not isinstance(panels, list) or not panels or not isinstance(derived, list):
        fail(args.source, "requires feature_descriptions, non-empty panels, and derived_features arrays")

    metadata = set()
    for item in descriptions:
        if not isinstance(item, dict) or not all(isinstance(item.get(key), str) and item[key] for key in ("id", "label", "description")):
            fail(args.source, "invalid feature description")
        if item["id"] in metadata:
            fail(args.source, f"duplicate feature description {item['id']}")
        metadata.add(item["id"])

    derived_ids = set()
    for item in derived:
        if not isinstance(item, dict) or not isinstance(item.get("id"), str) or not item["id"] or not isinstance(item.get("inputs"), list) or not isinstance(item.get("formula"), str):
            fail(args.source, "invalid derived feature")
        if item["id"] in derived_ids:
            fail(args.source, f"duplicate derived feature {item['id']}")
        derived_ids.add(item["id"])

    panel_rows: list[tuple[str, int]] = []
    feature_rows: list[tuple[str, str, str]] = []
    panel_ids = set()
    used = set()
    for panel in panels:
        if not isinstance(panel, dict) or not isinstance(panel.get("id"), str) or not panel["id"] or not isinstance(panel.get("n_components"), int) or panel["n_components"] < 1:
            fail(args.source, "invalid panel")
        panel_id = panel["id"]
        if panel_id in panel_ids:
            fail(args.source, f"duplicate panel {panel_id}")
        panel_ids.add(panel_id)
        panel_rows.append((panel_id, panel["n_components"]))
        groups = panel.get("weight_groups")
        if not isinstance(groups, list) or not groups:
            fail(args.source, f"panel {panel_id} requires non-empty weight_groups")
        group_ids = set()
        panel_features = set()
        for group in groups:
            if not isinstance(group, dict) or not isinstance(group.get("id"), str) or not group["id"] or not isinstance(group.get("features"), list) or not group["features"]:
                fail(args.source, f"invalid weight group in panel {panel_id}")
            group_id = group["id"]
            if group_id in group_ids:
                fail(args.source, f"duplicate weight group {panel_id}/{group_id}")
            group_ids.add(group_id)
            for feature in group["features"]:
                if not isinstance(feature, str) or not feature:
                    fail(args.source, f"invalid feature in {panel_id}/{group_id}")
                if feature not in metadata:
                    fail(args.source, f"feature {feature} lacks metadata")
                if feature in panel_features:
                    fail(args.source, f"duplicate panel feature {feature} in {panel_id}")
                panel_features.add(feature)
                used.add(feature)
                feature_rows.append((panel_id, group_id, feature))

    if used != metadata:
        fail(args.source, "feature descriptions must exactly match panel features")
    if not derived_ids.issubset(used):
        fail(args.source, "derived features must be used by a panel")

    lines = [
        "// Generated by scripts/generate_hdstats_pc_schema.py; do not edit.",
        "#ifndef __HDSTATS_PC_SCHEMA_H__",
        "#define __HDSTATS_PC_SCHEMA_H__",
        "namespace hdstats_pc_generated {",
        "static const generated_panel_t panels[] = {",
    ]
    lines += [f"  {{ {cpp(panel)}, {components} }}," for panel, components in panel_rows]
    lines += [
        "};",
        "static const int n_panels = sizeof(panels) / sizeof(panels[0]);",
        "static const generated_feature_t features[] = {",
    ]
    lines += [f"  {{ {cpp(panel)}, {cpp(group)}, {cpp(feature)} }}," for panel, group, feature in feature_rows]
    lines += [
        "};",
        "static const int n_features = sizeof(features) / sizeof(features[0]);",
        "}",
        "#endif",
        "",
    ]
    args.output.write_text("\n".join(lines))


if __name__ == "__main__":
    main()
